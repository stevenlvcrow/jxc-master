WITH ranked AS (
    SELECT id,
           row_number() OVER (
               PARTITION BY tenant_group_id, role_code
               ORDER BY created_at DESC NULLS LAST,
                        id DESC
           ) AS rn
    FROM sys_role
)
DELETE FROM sys_role rel
USING ranked
WHERE rel.id = ranked.id
  AND ranked.rn > 1;

